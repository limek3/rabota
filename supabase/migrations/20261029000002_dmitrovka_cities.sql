-- ════════════════════════════════════════════════════════════════════════
--  LEADUP CRM — города проекта «Дмитровка»: только Москва и Московская область
--
--  В окне лида Дмитровки поле «Город клиента» — из этих двух. Поменять список можно в «Проектах».
--  Нужен файл 20261017000003_project_cities.sql (колонка projects.regions).
--
--  Supabase → SQL Editor → вставить файл целиком → Run. Повторный запуск безопасен.
-- ════════════════════════════════════════════════════════════════════════

set local lock_timeout = '10s';

update public.projects
set regions = '["Москва", "Московская область"]'::jsonb,
    updated_at = now()
where deleted_at is null
  and regexp_replace(lower(name), '[^a-z0-9а-я]', '', 'g') = 'дмитровка'
  and coalesce(regions, '[]'::jsonb) is distinct from '["Москва", "Московская область"]'::jsonb;

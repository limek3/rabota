-- Аватар и имя коллеги должны меняться на экране, а не после перезапуска.
--
-- profiles не было в publication, поэтому смена имени или аватарки доезжала до
-- остальных только при полной перезагрузке приложения: данные в базе новые,
-- а в памяти у всех, кто уже открыл вкладку, — снимок с момента входа.
--
-- Фильтровать по workspace_id нельзя: у profiles его нет, профиль общий на все
-- воркспейсы. Ограничение делает RLS (policy profiles_read) — realtime уважает
-- её и отдаёт только тех, с кем ты делишь воркспейс.
alter publication supabase_realtime add table profiles;

-- workspace_members — по той же причине: смена роли или появление нового
-- участника иначе видны только после перезапуска.
alter publication supabase_realtime add table workspace_members;

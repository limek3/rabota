-- Опыт из резюме и сам файл резюме.
--
-- experience_text — блок «Опыт работы», выдернутый из резюме при разборе. Поле
-- exp отвечает на «сколько» («6 лет 5 месяцев»), а нанимают по «что делал».
-- Раньше этот текст уезжал в note и забивал заметку на шестьдесят строк —
-- заметка нужна рекрутёру под его собственные мысли, а не под выгрузку.
--
-- resume_data — содержимое файла как data URI. До сих пор в БД лежали только
-- имя, размер и дата: после перезагрузки страницы файл исчезал, и кнопка
-- «скачать» скачивать было нечего. Тот же приём уже применён к avatar (см.
-- 20260716000003): для файлов в сотни килобайт отдельный бакет не оправдан.
-- Клиент не кладёт сюда ничего крупнее MAX_PERSISTED_RESUME (900 КБ); когда
-- понадобятся большие файлы, колонка станет ссылкой на объект в storage и тип
-- не изменится.
alter table public.candidates
  add column if not exists experience_text text,
  add column if not exists resume_data text;

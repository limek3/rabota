-- Роль «руководитель» — расщепление owner на две работы.
--
-- До сих пор owner значил сразу и «владелец воркспейса» (тариф, удаление,
-- состав команды), и «руководитель» (видит все сделки, а не только свои) —
-- см. lib/store.tsx: isManager = meRole === "owner". Поэтому сделать человека
-- руководителем можно было единственным способом: отдать ему весь воркспейс
-- вместе с оплатой и кнопкой «удалить». Это не роль, это заложник.
--
-- Теперь три роли:
--   owner  — один, создатель. Тариф, удаление воркспейса, раздача ролей.
--   lead   — видит и ведёт любые сделки. Без денег и без раздачи ролей.
--   member — только свои сделки.
alter type member_role add value if not exists 'lead';

-- Политики update на workspace_members не было вовсе: select/insert/delete есть,
-- update — нет. Без неё смена роли не «запрещена с ошибкой», а молча не
-- срабатывает: RLS отказывает по умолчанию, клиент получает 0 изменённых строк
-- и считает, что всё прошло.
--
-- using  — какие строки owner вправе трогать: любые, кроме строки самого owner.
-- with check — во что их вправе превращать: в любую роль, кроме owner.
--
-- Отсюда три правила разом, и ни одно не нужно дублировать в клиенте:
-- роли раздаёт только owner; себя разжаловать нельзя; второго owner не создать.
create policy wm_update on workspace_members for update to authenticated
  using       (is_owner(workspace_id) and role <> 'owner')
  with check  (is_owner(workspace_id) and role <> 'owner');

-- Двусторонняя синхронизация Google Sheets.
--
-- До сих пор синк был в одну сторону: приложение перезаписывало лист, а правки
-- в самом листе терялись на следующей выгрузке. Теперь перед перезаписью
-- Edge Function sync-sheet сначала забирает правки из листа в базу (pullEdits),
-- и лишь потом пишет лист заново.
--
-- Чтобы отличить «поправили в таблице» от «поправили в приложении», функции
-- нужна опорная точка — что именно она в лист записала в прошлый раз. Держим её
-- здесь снимком: id контакта → значения редактируемых колонок. Ячейка в листе
-- разошлась со снимком ⇒ её тронул человек ⇒ забираем в базу; совпала ⇒ значение
-- приедет из приложения на прямой выгрузке.
--
-- Пишет и читает снимок только функция сервисным ключом (RLS в обход); клиент
-- его не трогает. Поэтому политики менять не нужно.
--
-- ВНИМАНИЕ: применять через SQL editor в панели Supabase, НЕ через db push.
-- После этого передеплоить функцию: supabase functions deploy sync-sheet

alter table public.crm_sheets
  add column if not exists last_snapshot jsonb not null default '{}'::jsonb;

comment on column public.crm_sheets.last_snapshot is
  'Снимок редактируемых колонок при прошлой выгрузке (id → значения). Опора обратного синка: по нему функция отличает правки в листе от правок в приложении.';
